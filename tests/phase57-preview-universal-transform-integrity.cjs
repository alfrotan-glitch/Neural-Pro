const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const playerPath = path.join(root, 'src/components/player/VideoPlayer.tsx');
const hookPath = path.join(root, 'src/features/video-studio/playback/hooks/usePreviewTransformInteraction.ts');
const servicePath = path.join(root, 'src/features/video-studio/playback/services/previewTransformInteractionService.ts');
const modelPath = path.join(root, 'src/features/video-studio/playback/services/clipTransformModel.ts');
for (const file of [playerPath, hookPath, servicePath, modelPath]) assert.equal(fs.existsSync(file), true, `Missing ${file}`);
const player = fs.readFileSync(playerPath, 'utf8');
const hook = fs.readFileSync(hookPath, 'utf8');
const service = fs.readFileSync(servicePath, 'utf8');
const model = fs.readFileSync(modelPath, 'utf8');
assert.equal((player.match(/data-preview-transformable="true"/g) || []).length, 4,
  'all four preview transform targets must be marked transformable');
assert.match(player, /data-preview-asset-kind="caption"/);
assert.match(player, /data-preview-asset-kind="audio"/);
assert.match(player, /data-preview-asset-kind={clip\.properties\.videoUrl \? 'video' : clip\.properties\.imageUrl \? 'image' : 'media'}/);
assert.match(player, /data-preview-asset-kind="effect"/);
assert.match(player, /handleMoveMouseDown\(e, clip\)/, 'preview assets must have move affordance');
assert.match(player, /PreviewResizeHandles/, 'preview assets must have resize affordance');
assert.match(player, /handleRotateMouseDown\(e, clip\)/, 'preview asset family must share rotation affordance');
assert.match(hook, /type PreviewTransformDragType = 'move' \| 'resize' \| 'rotate'/);
assert.match(hook, /AutoKeyframeTransformCommand|createTracksSnapshotCommand/);
assert.match(hook, /autoKeyframeEnabled/);
assert.match(service, /const MIN_SCALE = 10;/);
assert.match(service, /const MAX_SCALE = 400;/);
assert.match(service, /const anchorLocalX = handle\.includes\('w'\)/);
assert.match(service, /const anchorLocalY = handle\.includes\('n'\)/);
assert.match(model, /transform origin is always the element center/i);
assert.match(model, /scaleX/);
assert.match(model, /scaleY/);
assert.match(model, /scale\(\$\{sx\}, \$\{sy\}\)/);
console.log('PHASE57_PREVIEW_UNIVERSAL_TRANSFORM_INTEGRITY=PASS');
